# 함수들 (기존 그대로)
def map_ncs_code(code_str: str) -> str:
    """
    NCS코드 문자열에서 앞 7자리(또는 8자리)를 추출해 직종명으로 변환.
    매핑이 없으면 원본 코드 반환.
    """
    if not code_str:
        return ""
    code = str(code_str).strip()
    
    # 7자리 코드 직접 매핑 시도
    if code in NCS_JOB_MAP:
        return NCS_JOB_MAP[code]
        
    # 앞 8자리, 7자리 순서로 매핑 시도 (코드 앞부분만 비교)
    for length in [8, 7]:
        prefix = code[:length]
        if prefix in NCS_JOB_MAP:
            return NCS_JOB_MAP[prefix]
            
    return code  # 매핑 없으면 원본 반환

